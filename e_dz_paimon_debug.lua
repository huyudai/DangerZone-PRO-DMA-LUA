callback.on_draw(function()
  local enable = settings[keys.enable]
  if enable == nil then enable = true end
  if not enable then return end
  if not loaded then return end
  if #frames == 0 then return end

  local fps = tonumber(settings[keys.fps]) or FPS
  local speed = tonumber(settings[keys.speed]) or 1.0
  if fps < 0.01 then fps = 0.01 end
  if speed < 0.01 then speed = 0.01 end

  local effective_fps = fps * speed
  local interval = 1.0 / effective_fps

  local now = os.clock()
  if now - last_frame_time >= interval then
    last_frame_time = now
    frame_index = frame_index + 1
    if frame_index > TOTAL_FRAMES then
      frame_index = 1
    end
  end

  local f = frames[frame_index]
  if not f then
    for _ = 1, TOTAL_FRAMES do
      frame_index = frame_index + 1
      if frame_index > TOTAL_FRAMES then frame_index = 1 end
      f = frames[frame_index]
      if f then break end
    end
    if not f then return end
  end

  local x = tonumber(settings[keys.x]) or 100
  local y = tonumber(settings[keys.y]) or 100
  local scale = tonumber(settings[keys.scale]) or 1.0

  local dw = f.w * scale
  local dh = f.h * scale

  draw.image(f.id, x, y, dw, dh)
end)

